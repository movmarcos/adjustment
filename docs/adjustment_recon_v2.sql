SELECT
    a.DEV_ADJ_ID,
    a.COBID,
    a.PROCESS_TYPE,
    a.ADJUSTMENT_TYPE,
    a.ENTITY_CODE,
    a.DEPARTMENT_CODE,
    a.BOOK_CODE,
    a.TRADE_CODE,
    a.TRADE_TYPOLOGY,
    a.INSTRUMENT_CODE,
    a.SIMULATION_NAME,
    a.MEASURE_TYPE_CODE,
    a.SCALE_FACTOR,
    a.SOURCE_COBID,
    a.RECORD_COUNT,                       -- caution: shared per run batch, not per adj
    av.ADJUSTMENT_VALUE,
    o.ORIGINAL_VALUE,
    s.SOURCE_VALUE,
    tc.TARGET_COMBINED_VALUE,
    -- Expected DELTA the engine should have written
    CASE
        WHEN a.ADJUSTMENT_TYPE = 'Direct' THEN a.ADJUSTMENT_VALUE_IN_USD
        WHEN a.ADJUSTMENT_TYPE = 'Flatten' THEN -o.ORIGINAL_VALUE
        WHEN a.ADJUSTMENT_TYPE = 'Scale' AND a.SOURCE_COBID = a.COBID
             THEN o.ORIGINAL_VALUE * (a.SCALE_FACTOR - 1)
        WHEN a.ADJUSTMENT_TYPE = 'Scale'                       -- cross-day scale
             THEN s.SOURCE_VALUE * a.SCALE_FACTOR
        WHEN a.ADJUSTMENT_TYPE = 'Roll'
             THEN s.SOURCE_VALUE - (tc.TARGET_COMBINED_VALUE - av.ADJUSTMENT_VALUE)
    END AS EXPECTED_ADJ_VALUE,
    CASE
        WHEN a.ADJUSTMENT_TYPE = 'Direct'
             THEN av.ADJUSTMENT_VALUE - a.ADJUSTMENT_VALUE_IN_USD
        WHEN a.ADJUSTMENT_TYPE = 'Roll'
             THEN tc.TARGET_COMBINED_VALUE - s.SOURCE_VALUE    -- invariant: combined(target)=adjusted(source)
        WHEN a.ADJUSTMENT_TYPE = 'Flatten'
             THEN av.ADJUSTMENT_VALUE + o.ORIGINAL_VALUE
        WHEN a.ADJUSTMENT_TYPE = 'Scale' AND a.SOURCE_COBID = a.COBID
             THEN av.ADJUSTMENT_VALUE - o.ORIGINAL_VALUE * (a.SCALE_FACTOR - 1)
        WHEN a.ADJUSTMENT_TYPE = 'Scale'
             THEN av.ADJUSTMENT_VALUE - s.SOURCE_VALUE * a.SCALE_FACTOR
    END AS RECON_DIFFERENCE,
    CASE
        WHEN a.ADJUSTMENT_TYPE = 'Direct' THEN
            CASE
                WHEN a.ADJUSTMENT_VALUE_IN_USD IS NULL THEN 'LEGACY DIRECT (pre-split) — not comparable'
                WHEN av.ADJUSTMENT_VALUE IS NULL THEN 'MISSING ADJUSTMENT'
                WHEN ABS(av.ADJUSTMENT_VALUE - a.ADJUSTMENT_VALUE_IN_USD) < 0.01
                     THEN 'RECONCILED'
                ELSE 'BREAK'
            END
        WHEN a.ADJUSTMENT_TYPE = 'Roll' THEN
            CASE
                WHEN s.SOURCE_VALUE IS NULL AND av.ADJUSTMENT_VALUE IS NULL
                     THEN 'NO DATA IN SCOPE (check filter values)'
                WHEN s.SOURCE_VALUE IS NULL          THEN 'MISSING ROLL SOURCE'
                WHEN tc.TARGET_COMBINED_VALUE IS NULL THEN 'MISSING TARGET DATA'
                WHEN ABS(tc.TARGET_COMBINED_VALUE - s.SOURCE_VALUE) < 0.01
                     THEN 'RECONCILED'
                ELSE 'BREAK'
            END
        WHEN a.ADJUSTMENT_TYPE = 'Scale' AND a.SOURCE_COBID = a.COBID THEN
            CASE
                WHEN o.ORIGINAL_VALUE IS NULL AND av.ADJUSTMENT_VALUE IS NULL
                     THEN 'NO DATA IN SCOPE (check filter values)'
                WHEN av.ADJUSTMENT_VALUE IS NULL
                     AND ABS(COALESCE(o.ORIGINAL_VALUE,0) * (a.SCALE_FACTOR - 1)) < 0.01
                     THEN 'NO-OP (zero delta, factor=1)'
                WHEN av.ADJUSTMENT_VALUE IS NULL     THEN 'MISSING ADJUSTMENT'
                WHEN o.ORIGINAL_VALUE IS NULL        THEN 'MISSING ORIGINAL'
                WHEN ABS(av.ADJUSTMENT_VALUE - o.ORIGINAL_VALUE * (a.SCALE_FACTOR - 1)) < 0.01
                     THEN 'RECONCILED'
                ELSE 'BREAK'
            END
        WHEN a.ADJUSTMENT_TYPE = 'Scale' THEN        -- cross-day scale
            CASE
                WHEN s.SOURCE_VALUE IS NULL AND av.ADJUSTMENT_VALUE IS NULL
                     THEN 'NO DATA IN SCOPE (check filter values)'
                WHEN av.ADJUSTMENT_VALUE IS NULL     THEN 'MISSING ADJUSTMENT'
                WHEN s.SOURCE_VALUE IS NULL          THEN 'MISSING SOURCE'
                WHEN ABS(av.ADJUSTMENT_VALUE - s.SOURCE_VALUE * a.SCALE_FACTOR) < 0.01
                     THEN 'RECONCILED'
                ELSE 'BREAK'
            END
        ELSE -- Flatten
            CASE
                WHEN o.ORIGINAL_VALUE IS NULL AND av.ADJUSTMENT_VALUE IS NULL
                     THEN 'NO DATA IN SCOPE (check filter values)'
                WHEN av.ADJUSTMENT_VALUE IS NULL     THEN 'MISSING ADJUSTMENT'
                WHEN o.ORIGINAL_VALUE IS NULL        THEN 'MISSING ORIGINAL'
                WHEN ABS(av.ADJUSTMENT_VALUE + o.ORIGINAL_VALUE) < 0.01
                     THEN 'RECONCILED'
                ELSE 'BREAK'
            END
    END AS RECON_STATUS,
    a.REASON
FROM adj a
LEFT JOIN adjustment_values av ON av.PROCESS_TYPE = a.PROCESS_TYPE
                              AND av.ADJUSTMENT_ID = a.DEV_ADJ_ID
LEFT JOIN original_values  o  ON o.DEV_ADJ_ID  = a.DEV_ADJ_ID
LEFT JOIN source_values    s  ON s.DEV_ADJ_ID  = a.DEV_ADJ_ID
LEFT JOIN target_combined  tc ON tc.DEV_ADJ_ID = a.DEV_ADJ_ID
ORDER BY a.COBID, a.PROCESS_TYPE, a.DEV_ADJ_ID;
