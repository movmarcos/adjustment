              AND (td.TRADE_TYPOLOGY = a.TRADE_TYPOLOGY OR a.TRADE_TYPOLOGY IS NULL)
              AND (td.STRATEGY = a.STRATEGY OR a.STRATEGY IS NULL)))
     AND ((a.SIMULATION_NAME IS NULL AND a.SIMULATION_SOURCE IS NULL) OR EXISTS (
            SELECT 1 FROM DIMENSION.STRESS_SIMULATION ss
            WHERE ss.STRESS_SIMULATION_KEY = COALESCE(f.STRESS_SIMULATION_KEY, -1)
              AND (ss.STRESS_SIMULATION_NAME = a.SIMULATION_NAME OR a.SIMULATION_NAME IS NULL)
              AND (ss.SIMULATION_SOURCE = a.SIMULATION_SOURCE OR a.SIMULATION_SOURCE IS NULL)))
     AND (a.INSTRUMENT_CODE IS NULL OR EXISTS (
            SELECT 1 FROM DIMENSION.COMMON_INSTRUMENT ci
            WHERE ci.COMMON_INSTRUMENT_KEY = COALESCE(f.COMMON_INSTRUMENT_KEY, -1)
              AND ci.INSTRUMENT_CODE = a.INSTRUMENT_CODE))
    WHERE a.PROCESS_TYPE = 'Stress'
    GROUP BY a.DEV_ADJ_ID

    UNION ALL
    -- Sensitivity (measure type via DIMENSION.MEASURE_TYPE — fact has KEY only)
    SELECT a.DEV_ADJ_ID, SUM(f.MEASURE_VALUE_USD)
    FROM adj a
    JOIN FACT.SENSITIVITY_MEASURES f
      ON f.COBID = a.COBID
     AND EXISTS (SELECT 1 FROM DIMENSION.ENTITY e
                 WHERE e.ENTITY_KEY = COALESCE(f.ENTITY_KEY, -1)
                   AND e.ENTITY_CODE = a.ENTITY_CODE)
     AND ((a.BOOK_CODE IS NULL AND a.DEPARTMENT_CODE IS NULL) OR EXISTS (
