     AND (a.MEASURE_TYPE_CODE IS NULL OR EXISTS (
            SELECT 1 FROM DIMENSION.MEASURE_TYPE mt
            WHERE mt.MEASURE_TYPE_KEY = COALESCE(f.MEASURE_TYPE_KEY, -1)
              AND mt.MEASURE_TYPE_CODE = a.MEASURE_TYPE_CODE))
     AND (a.INSTRUMENT_CODE IS NULL OR f.INSTRUMENT_CODE = a.INSTRUMENT_CODE)
    WHERE a.PROCESS_TYPE = 'FRTB'
    GROUP BY a.DEV_ADJ_ID

    UNION ALL
    -- FRTBDRC
    SELECT a.DEV_ADJ_ID, SUM(f.JTD_LOSS_USD)
    FROM adj a
    JOIN FACT.FRTBSA_DRC_MEASURES f
      ON f.COBID = a.COBID
     AND f.ENTITY_CODE = a.ENTITY_CODE
     AND ((a.BOOK_CODE IS NULL AND a.DEPARTMENT_CODE IS NULL) OR EXISTS (
            SELECT 1 FROM DIMENSION.BOOK bk
            WHERE bk.BOOK_KEY = COALESCE(f.BOOK_KEY, -1)
