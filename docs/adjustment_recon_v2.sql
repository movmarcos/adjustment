            WHERE bk.BOOK_KEY = COALESCE(f.BOOK_KEY, -1)
              AND (bk.BOOK_CODE = a.BOOK_CODE OR a.BOOK_CODE IS NULL)
              AND (bk.DEPARTMENT_CODE = a.DEPARTMENT_CODE OR a.DEPARTMENT_CODE IS NULL)))
     AND ((a.TRADE_CODE IS NULL AND a.TRADE_TYPOLOGY IS NULL AND a.STRATEGY IS NULL) OR EXISTS (
