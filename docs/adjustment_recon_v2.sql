              AND (td.STRATEGY = a.STRATEGY OR a.STRATEGY IS NULL)))
     AND (a.MEASURE_TYPE_CODE IS NULL OR f.MEASURE_TYPE_CODE = a.MEASURE_TYPE_CODE)
    WHERE a.PROCESS_TYPE = 'FRTBRRAO'
    GROUP BY a.DEV_ADJ_ID
